#!/bin/sh
# Writes the repo-root .env for the all-in-one Oracle stack. Generates every
# secret it can and asks for the rest. Run once on the server:
#   cd ~/notetaker/deploy/oracle && ./init-env.sh
set -e
cd "$(dirname "$0")"
ENV_FILE=../../.env

if [ -f "$ENV_FILE" ]; then
  echo "$ENV_FILE already exists; edit it by hand, or delete it to start over."
  exit 1
fi

ask() { # ask VAR "question" [default]
  printf '%s%s: ' "$2" "${3:+ [$3]}"
  read -r answer
  eval "$1=\${answer:-\$3}"
}

IP=$(curl -fsS https://api.ipify.org || true)
echo "Public IP: ${IP:-unknown}"
echo "Website address: a subdomain you point at this IP (A record), e.g. notes.syncup.in."
echo "No DNS access? ${IP:+$(echo "$IP" | tr . -).sslip.io} works with no setup."
ask APP_DOMAIN "Website domain" "${IP:+$(echo "$IP" | tr . -).sslip.io}"
ask ALLOWED_EMAIL_DOMAINS "Company email domain(s) allowed to sign in" "syncup.in"
ask ADMIN_EMAILS "Admin email(s), comma-separated" ""
ask BOT_EMAIL "Bot Google account" "notetaker@syncup.in"
ask GOOGLE_CLIENT_ID "Google OAuth client ID" ""
ask GOOGLE_CLIENT_SECRET "Google OAuth client secret" ""
ask GEMINI_API_KEY "Gemini API key (aistudio.google.com)" ""
ask ASSEMBLYAI_API_KEY "AssemblyAI API key" ""

PG_PASSWORD=$(openssl rand -hex 24)
umask 077
cat > "$ENV_FILE" <<EOF
# Generated by deploy/oracle/init-env.sh on $(date +%F). Never commit this file.
APP_DOMAIN=$APP_DOMAIN
APP_URL=https://$APP_DOMAIN
AUTH_URL=https://$APP_DOMAIN
AUTH_SECRET=$(openssl rand -base64 33)

POSTGRES_PASSWORD=$PG_PASSWORD
DATABASE_URL=postgres://notetaker:$PG_PASSWORD@db:5432/notetaker

GOOGLE_CLIENT_ID=$GOOGLE_CLIENT_ID
GOOGLE_CLIENT_SECRET=$GOOGLE_CLIENT_SECRET
TOKEN_ENCRYPTION_KEY=$(openssl rand -base64 32)

ALLOWED_EMAIL_DOMAINS=$ALLOWED_EMAIL_DOMAINS
ALLOWED_EMAILS=
ADMIN_EMAILS=$ADMIN_EMAILS
BOT_EMAIL=$BOT_EMAIL

ASSEMBLYAI_API_KEY=$ASSEMBLYAI_API_KEY
GEMINI_API_KEY=$GEMINI_API_KEY
# Free-tier friendly: flash-lite has the largest free daily quota, and live
# notes every 2 minutes is ~30 calls per meeting-hour.
LIVE_NOTES_MODEL=gemini-2.5-flash-lite
LIVE_NOTES_INTERVAL_SECONDS=120
REPORT_MODEL=gemini-2.5-flash

RECORDING=video
MAX_CONCURRENT_BOTS=3
TZ=Asia/Kolkata
EOF

# docker compose reads ./.env for the \${...} values in docker-compose.yml.
ln -sf ../../.env .env

echo
echo "Wrote $ENV_FILE. Add these redirect URIs to the Google OAuth client:"
echo "  https://$APP_DOMAIN/api/auth/callback/google"
echo "  https://$APP_DOMAIN/api/bot/callback"
